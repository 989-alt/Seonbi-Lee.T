const ROMAN = ["0", "I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X", "XI", "XII", "XIII", "XIV", "XV", "XVI", "XVII", "XVIII", "XIX", "XX", "XXI"];
const COURT = ["page", "knight", "queen", "king"];
const COURT_KO = ["시종", "기사", "여왕", "왕"];

const toCard = (id: string, group: TarotGroup, rank: number, numberOrRank: string, [nameKo, nameEn, keywords, tone, upright, reversed, doUpright, doReversed]: Row): TarotCard => ({
  id, group, rank, numberOrRank, nameKo, nameEn, keywords, tone, upright, reversed, doUpright, doReversed, front: `/fortune/tarot/${id}.webp`,
});

const minor = (group: Exclude<TarotGroup, "major">, rows: Row[]) =>
  rows.map((r, i) => toCard(`${group}-${i < 10 ? String(i + 1).padStart(2, "0") : COURT[i - 10]}`, group, i + 1, i === 0 ? "A" : i < 10 ? String(i + 1) : COURT_KO[i - 10], r));

export const TAROT_CARDS: TarotCard[] = [
  ...MAJOR.map((r, i) => toCard(`major-${String(i).padStart(2, "0")}`, "major", i, ROMAN[i], r)),
  ...minor("wands", WANDS),
  ...minor("cups", CUPS),
  ...minor("swords", SWORDS),
  ...minor("pentacles", PENTACLES),
];

const BY_ID = new Map(TAROT_CARDS.map((c) => [c.id, c]));
export function cardById(id: string): TarotCard {
  const c = BY_ID.get(id);
  if (!c) throw new Error(`없는 타로 카드: ${id}`);
  return c;
}
